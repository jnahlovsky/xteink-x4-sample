// Sprite sheet dimensions
#define ICON_SPRITE_WIDTH 640		// Total sprite sheet width
#define ICON_SPRITE_HEIGHT 80		// Sprite sheet height
#define CATEGORY_ICON_WIDTH 80	// Individual icon width
#define CATEGORY_ICON_HEIGHT 80 // Individual icon height
#define ICON_COUNT 8						// Number of icons in sprite

// Category icon indices (matches order in convert_cards_csv_to_cpp.py)
// Order: Emotions, Fantasy, Relationships, MyBody, School, Nature, WhatIf, Secrets
enum IconIndex
{
	ICON_EMOTIONS = 0,			// CAT_EMOTIONS
	ICON_FANTASY = 1,				// CAT_FANTASY
	ICON_RELATIONSHIPS = 2, // CAT_RELATIONSHIPS
	ICON_MYBODY = 3,				// CAT_MYBODY
	ICON_SCHOOL = 4,				// CAT_SCHOOL
	ICON_NATURE = 5,				// CAT_NATURE
	ICON_WHATIF = 6,				// CAT_WHATIF
	ICON_SECRETS = 7				// CAT_SECRETS
};

/**
 * Extract a single icon from the sprite sheet
 * @param iconIndex Icon index (0-7)
 * @param buffer Output buffer (must be at least 800 bytes for 80x80 1-bit image)
 */
inline void extractIcon(uint8_t iconIndex, uint8_t *buffer)
{
	if (iconIndex >= ICON_COUNT)
		return;

	const int bytesPerRow = ICON_SPRITE_WIDTH / 8;		 // 640/8 = 80 bytes per row
	const int iconByteWidth = CATEGORY_ICON_WIDTH / 8; // 80/8 = 10 bytes per icon
	const int iconStartByte = iconIndex * iconByteWidth;

	// Extract each row of the icon
	for (int row = 0; row < CATEGORY_ICON_HEIGHT; row++)
	{
		const int spriteRowOffset = row * bytesPerRow;
		const int iconRowOffset = row * iconByteWidth;

		// Copy 10 bytes (80 pixels) from sprite sheet to buffer
		for (int col = 0; col < iconByteWidth; col++)
		{
			buffer[iconRowOffset + col] = pgm_read_byte(&icons[spriteRowOffset + iconStartByte + col]);
		}
	}
}

/**
 * Get icon index from category enum
 * Maps Category enum to IconIndex
 */
inline uint8_t categoryToIconIndex(uint8_t category)
{
	// Category enum matches IconIndex order (both defined in same order)
	return category;
}

